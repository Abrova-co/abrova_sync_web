#!/usr/bin/env python3
"""Embeds the Abrova Sync web SDK's browser build in Dart (lib/src/sync_web_sdk.g.dart).

  tool/embed_sdk.py <path to abrova-sync-web> 

It is code only the web build reaches, so phone and computer apps don't carry it
(an asset would be copied into every app).
"""
import json, sys, pathlib
src = pathlib.Path(sys.argv[1])
js = (src / 'dist' / 'index.umd.js').read_text()
version = json.loads((src / 'package.json').read_text())['version']
assert "'''" not in js, 'the build contains three quotes in a row: use another delimiter'
out = pathlib.Path(__file__).resolve().parent.parent / 'lib' / 'src' / 'sync_web_sdk.g.dart'
out.write_text(
    "// GENERATED by tool/embed_sdk.py from @abrova/sync-web " + version + ". Do not edit.\n"
    "// ignore_for_file: lines_longer_than_80_chars\n\n"
    "/// Version of the embedded web SDK.\n"
    "const syncWebSdkVersion = '" + version + "';\n\n"
    "/// Its browser build (UMD, global `AbrovaSync`).\n"
    "const syncWebSdkJs = r'''" + js + "''';\n")
print('embedded @abrova/sync-web', version, len(js), 'bytes ->', out)
